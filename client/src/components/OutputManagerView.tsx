import { useEffect, useState } from 'react'
import type { OutputFile } from '../../../shared/types'
import { fetchOutputPreview, listOutputs, openOutputFolder, openOutputPath, updateOutputsDir } from '../api'

interface OutputManagerViewProps {
  brandId?: string
}

export function OutputManagerView({ brandId }: OutputManagerViewProps) {
  const [baseDir, setBaseDir] = useState('')
  const [files, setFiles] = useState<OutputFile[]>([])
  const [category, setCategory] = useState<'All' | 'Lead-Hunt' | 'Marketing'>('All')
  const [loading, setLoading] = useState(false)
  const [error, setError] = useState<string | null>(null)
  const [preview, setPreview] = useState<{ path: string; name: string; content: string } | null>(null)
  const [editingDir, setEditingDir] = useState(false)
  const [dirInput, setDirInput] = useState('')

  const load = async () => {
    setLoading(true)
    setError(null)
    try {
      const data = await listOutputs(brandId)
      setBaseDir(data.dir)
      setDirInput(data.dir)
      setFiles(data.files)
    } catch (err) {
      setError(err instanceof Error ? err.message : String(err))
    } finally {
      setLoading(false)
    }
  }

  useEffect(() => {
    void load()
  }, [brandId])

  const filtered = files.filter((f) => {
    if (category === 'All') return true
    return f.category === category
  })

  const handleOpenFolder = async (cat?: string) => {
    try {
      await openOutputFolder(cat, brandId)
    } catch (err) {
      setError(err instanceof Error ? err.message : String(err))
    }
  }

  const handleOpenFile = async (filePath: string) => {
    try {
      await openOutputPath(filePath)
    } catch (err) {
      setError(err instanceof Error ? err.message : String(err))
    }
  }

  const handlePreview = async (file: OutputFile) => {
    try {
      const res = await fetchOutputPreview(file.path)
      setPreview({ path: file.path, name: file.name, content: res.content })
    } catch (err) {
      setError(err instanceof Error ? err.message : String(err))
    }
  }

  const handleSaveDir = async () => {
    if (!dirInput.trim()) return
    try {
      const res = await updateOutputsDir(dirInput.trim())
      setBaseDir(res.dir)
      setEditingDir(false)
      load()
    } catch (err) {
      setError(err instanceof Error ? err.message : String(err))
    }
  }

  return (
    <div className="management-view output-manager-view">
      <div className="management-header">
        <div>
          <h2>Output Manager <span className="badge-verified" style={{ fontSize: '12px', verticalAlign: 'middle', marginLeft: '6px' }}>{brandId === 'the-solver-agency' ? 'The Solver Agency' : 'Growthifyx'}</span></h2>
          <p className="management-subtitle">
            Saved files, CSV exports, and marketing drafts generated by Lead Hunt and Marketing.
          </p>
        </div>
        <div className="btn-group">
          <button type="button" className="btn-secondary" onClick={load} disabled={loading}>
            Refresh
          </button>
          <button
            type="button"
            className="btn-primary"
            onClick={() => handleOpenFolder(category === 'All' ? undefined : category)}
          >
            Open Folder ↗
          </button>
        </div>
      </div>

      {error && <div className="alert-box error">{error}</div>}

      {/* Output Directory Bar */}
      <div className="card dir-bar">
        <div className="dir-info">
          <span className="dir-label">📁 Output Directory:</span>
          {editingDir ? (
            <div className="dir-edit-wrap">
              <input
                type="text"
                value={dirInput}
                onChange={(e) => setDirInput(e.target.value)}
                className="dir-input"
              />
              <button type="button" className="btn-sm btn-primary" onClick={handleSaveDir}>
                Save
              </button>
              <button type="button" className="btn-sm btn-secondary" onClick={() => setEditingDir(false)}>
                Cancel
              </button>
            </div>
          ) : (
            <span className="dir-path" title={baseDir}>
              <code>{baseDir}</code>
              <button type="button" className="btn-link" onClick={() => setEditingDir(true)}>
                Change
              </button>
            </span>
          )}
        </div>
        <div className="dir-quick-links">
          <button type="button" className="btn-sm btn-secondary" onClick={() => handleOpenFolder('Lead-Hunt')}>
            Lead-Hunt Folder
          </button>
          <button type="button" className="btn-sm btn-secondary" onClick={() => handleOpenFolder('Marketing')}>
            Marketing Folder
          </button>
        </div>
      </div>

      {/* Tabs */}
      <div className="tab-bar">
        <button
          type="button"
          className={`tab-btn ${category === 'All' ? 'active' : ''}`}
          onClick={() => setCategory('All')}
        >
          All Files ({files.length})
        </button>
        <button
          type="button"
          className={`tab-btn ${category === 'Lead-Hunt' ? 'active' : ''}`}
          onClick={() => setCategory('Lead-Hunt')}
        >
          Lead-Hunt ({files.filter((f) => f.category === 'Lead-Hunt').length})
        </button>
        <button
          type="button"
          className={`tab-btn ${category === 'Marketing' ? 'active' : ''}`}
          onClick={() => setCategory('Marketing')}
        >
          Marketing ({files.filter((f) => f.category === 'Marketing').length})
        </button>
      </div>

      {/* Files Grid / List */}
      <div className="card table-container">
        {filtered.length === 0 ? (
          <div className="empty-state">
            <p>No files found in this category.</p>
            <span className="empty-subtext">
              Files generated by Lead Hunt or Marketing workflows will appear here automatically.
            </span>
          </div>
        ) : (
          <table className="data-table">
            <thead>
              <tr>
                <th>File Name</th>
                <th>Category</th>
                <th>Size</th>
                <th>Date Modified</th>
                <th style={{ textAlign: 'right' }}>Actions</th>
              </tr>
            </thead>
            <tbody>
              {filtered.map((file) => (
                <tr key={file.id}>
                  <td>
                    <div className="file-name-cell">
                      <span className="file-icon">
                        {file.ext === '.csv' ? '📊' : file.ext === '.json' ? '📦' : '📄'}
                      </span>
                      <strong>{file.name}</strong>
                    </div>
                  </td>
                  <td>
                    <span className={`badge-scope scope-${file.category.toLowerCase()}`}>
                      {file.category}
                    </span>
                  </td>
                  <td>{(file.size / 1024).toFixed(1)} KB</td>
                  <td>{new Date(file.updatedAt).toLocaleString()}</td>
                  <td style={{ textAlign: 'right' }}>
                    <div className="btn-group-sm" style={{ justifyContent: 'flex-end' }}>
                      <button
                        type="button"
                        className="btn-sm btn-secondary"
                        onClick={() => handlePreview(file)}
                      >
                        Preview
                      </button>
                      <button
                        type="button"
                        className="btn-sm btn-primary"
                        onClick={() => handleOpenFile(file.path)}
                      >
                        Open ↗
                      </button>
                    </div>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
      </div>

      {/* File Preview Modal */}
      {preview && (
        <div className="modal-backdrop">
          <div className="modal-card modal-lg">
            <div className="modal-header">
              <h3>{preview.name} (Preview)</h3>
              <button type="button" className="btn-close" onClick={() => setPreview(null)}>
                ✕
              </button>
            </div>
            <div className="modal-body">
              <pre className="file-preview-pre">{preview.content}</pre>
            </div>
            <div className="modal-footer">
              <button type="button" className="btn-secondary" onClick={() => setPreview(null)}>
                Close
              </button>
              <button
                type="button"
                className="btn-primary"
                onClick={() => handleOpenFile(preview.path)}
              >
                Open with OS Default ↗
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  )
}
